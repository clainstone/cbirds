enum { GLYPH_COUNT = sizeof(GLYPHS) / sizeof(*GLYPHS) };

const char *font_glyph(char character) {
    char wanted = (char)toupper((unsigned char)character);
    for (int i = 0; i < GLYPH_COUNT; i++)
        if (GLYPHS[i].character == wanted) return GLYPHS[i].rows;
    return NULL;
}

int font_text_cells(const char *text) {
    int cells = 0;
    if (text == NULL) return 0;
    for (const char *c = text; *c != '\0'; c++) {
        const char *rows = font_glyph(*c);
        if (rows == NULL) continue;
        for (int i = 0; i < FONT_WIDTH * FONT_HEIGHT; i++)
            if (rows[i] == '#') cells++;
    }
    return cells;
}

int font_text_width(const char *text) {
    int glyphs = 0;
    if (text == NULL) return 0;
    for (const char *c = text; *c != '\0'; c++)
        if (font_glyph(*c) != NULL) glyphs++;
    return glyphs > 0 ? glyphs * FONT_ADVANCE - 1 : 0;
}
